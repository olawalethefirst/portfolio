import { fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { SocialProvider } from "@/src/cms/SocialProvider";
import { ContactList } from "./ContactList";
const { push } = vi.hoisted(() => ({ push: vi.fn() }));
vi.mock("next/navigation", () => ({ useRouter: () => ({ push }) }));
beforeEach(() => {
  push.mockReset();
  vi.stubGlobal("scrollTo", vi.fn());
  vi.stubGlobal("matchMedia", vi.fn(() => ({ matches: true, addEventListener: vi.fn(), removeEventListener: vi.fn(), addListener: vi.fn(), removeListener: vi.fn() })));
});
afterEach(() => vi.unstubAllGlobals());
it("searches saved profiles while the full contact preview includes the unfiltered collection", async () => {
  render(<SocialProvider><ContactList /></SocialProvider>);
  const search = screen.getByRole("searchbox", { name: "Search contact profiles" });
  fireEvent.change(search, { target: { value: "github" } });
  expect(screen.getAllByRole("listitem")).toHaveLength(1);
  fireEvent.click(screen.getByRole("button", { name: "Preview contact" }));
  expect(await screen.findByRole("heading", { name: "How would you like to connect?" })).toBeTruthy();
  expect(screen.getAllByRole("link", { name: /Visit .* profile/ })).toHaveLength(3);
  expect(screen.queryByRole("navigation", { name: "Content navigation" })).toBeNull();
  fireEvent.click(screen.getByRole("button", { name: "Exit preview" }));
  expect((screen.getByRole("searchbox", { name: "Search contact profiles" }) as HTMLInputElement).value).toBe("github");
  expect(document.activeElement).toBe(screen.getByRole("button", { name: "Preview contact" }));
  fireEvent.change(screen.getByRole("searchbox", { name: "Search contact profiles" }), { target: { value: "missing" } });
  expect(screen.getByText("No matching contact profiles")).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "Clear search" }));
  expect(screen.getAllByRole("listitem")).toHaveLength(3);
  fireEvent.click(screen.getByRole("button", { name: "New profile" }));
  expect(push).toHaveBeenCalledWith("/admin/contact/new");
});
it("keeps the complete form usable with no profiles and simulates submission truthfully", async () => {
  render(<SocialProvider initialRecords={[]}><ContactList /></SocialProvider>);
  expect(screen.getByText("No contact profiles yet")).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "Preview contact" }));
  await screen.findByRole("heading", { name: "How would you like to connect?" });
  expect(screen.queryByRole("link", { name: /Visit .* profile/ })).toBeNull();
  fireEvent.click(screen.getByRole("radio", { name: /^Hire/ }));
  fireEvent.click(screen.getByRole("button", { name: "Continue" }));
  fireEvent.change(screen.getByRole("textbox", { name: "Your goal" }), { target: { value: "Demonstrate the complete contact conversation." } });
  fireEvent.click(screen.getByRole("button", { name: "Continue" }));
  fireEvent.change(screen.getByRole("textbox", { name: "Name" }), { target: { value: "Ada Lovelace" } });
  fireEvent.change(screen.getByRole("textbox", { name: "Email" }), { target: { value: "ada@example.com" } });
  fireEvent.click(screen.getByRole("button", { name: "Send" }));
  expect(await screen.findByText("Demo submission complete. No message was sent.")).toBeTruthy();
  fireEvent.click(screen.getByRole("button", { name: "Submit another" }));
  await waitFor(() => expect(screen.getByRole("heading", { name: "How would you like to connect?" })).toBeTruthy());
});
